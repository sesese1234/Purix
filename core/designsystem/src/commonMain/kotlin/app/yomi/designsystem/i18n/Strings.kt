}

val LocalStrings = staticCompositionLocalOf<Strings> { EnglishStrings }

/**
 * Minimal positional formatter for the `%1$s` placeholders used above — Compose
 * Multiplatform has no `String.format`, and this keeps the templates familiar.
 */
fun String.format(vararg args: String): String {
    var result = this
    args.forEachIndexed { index, value ->
        result = result.replace("%${index + 1}\$s", value)
    }
    return result.replace("%%", "%")
}
